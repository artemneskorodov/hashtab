;===============================================================================
global cmp_key
;===============================================================================
section .text
;===============================================================================
cmp_key:
    ;---------------------------------------------------------------------------
    ; Generating all 1s in YMM3
    vpcmpeqd ymm3, ymm3, ymm3
    ;---------------------------------------------------------------------------
    ; Loading second key to YMM1
    vmovdqu ymm1, [rdi]
    ;---------------------------------------------------------------------------
    ; Comparing, setting to 1s bytes which are equal. Mask is written to YMM2, so bytes which are set to 1s in YMM2 are equal
    vpcmpeqb ymm2, ymm0, ymm1
    ;---------------------------------------------------------------------------
    ; Reversing YMM2 with xor operation with YMM3, so if strings are fully equal, YMM2 == 0
    vpxor ymm2, ymm2, ymm3
    ;---------------------------------------------------------------------------
    ; Checking if YMM2 is all zeros
    vptest ymm2, ymm2
    ;---------------------------------------------------------------------------
    ; Writing boolean result to AL
    setz al
    ;---------------------------------------------------------------------------
    ret
;===============================================================================
